const fs = require('fs'); const path = require('path');
const { JSDOM } = require('jsdom'); require('fake-indexeddb/auto');
const APP = __dirname;
async function main() {
  const html = fs.readFileSync(path.join(APP, 'index.html'), 'utf8');
  const dom = new JSDOM(html, { runScripts: 'outside-only', url: 'http://localhost/', pretendToBeVisual: true });
  const win = dom.window; const doc = win.document;
  win.indexedDB = global.indexedDB; win.IDBKeyRange = global.IDBKeyRange; win.confirm = () => true;
  for (const src of [...doc.querySelectorAll('script[src]')].map(s => s.getAttribute('src')).filter(s => s !== 'js/app.js')) win.eval(fs.readFileSync(path.join(APP, src), 'utf8'));
  const wait = (ms) => new Promise(r => setTimeout(r, ms));
  const fire = (el, v, ev = 'input') => { if (v !== undefined) el.value = v; el.dispatchEvent(new win.Event(ev)); };
  const go = async (h, ms = 100) => { win.location.hash = h; await win.Router.resolveRoute(); await wait(ms); };
  await win.DB.openDB(); await win.DB.ensureCounters();
  const custId = await win.DB.dbAdd('customers', { customerNo: 'C1', companyName: 'Shorr', status: 'Active', createdAt: new Date().toISOString() });
  await go('#/quotations/new');
  const rows = () => [...doc.querySelectorAll('#linesBody tr')];
  const q0 = rows()[0];
  fire(q0.querySelector('.ln-desc'), 'Priced item'); fire(q0.querySelector('.ln-price'), '1000'); fire(q0.querySelector('.ln-disc'), '10');
  doc.getElementById('addLineBtn') ? doc.getElementById('addLineBtn').click() : [...doc.querySelectorAll('button')].find(b => /Add Line/i.test(b.textContent)).click();
  await wait(30);
  let r1 = rows()[1];
  fire(r1.querySelector('.ln-desc'), 'In the lot item'); fire(r1.querySelector('.ln-disc'), '5');
  console.log('1 a line with a price keeps its discount box on:', !rows()[0].querySelector('.ln-disc').disabled && rows()[0].querySelector('.ln-disc').value === '10');
  console.log('2 a line with a blank price shows a blank, disabled discount box:', rows()[1].querySelector('.ln-disc').disabled === true && rows()[1].querySelector('.ln-disc').value === '', rows()[1].querySelector('.ln-disc').value);
  fire(rows()[1].querySelector('.ln-price'), '200');
  console.log('3 typing a price turns the discount box back on:', !rows()[1].querySelector('.ln-disc').disabled);
  fire(rows()[1].querySelector('.ln-price'), '0');
  console.log('4 clearing the price blanks it again:', rows()[1].querySelector('.ln-disc').disabled && rows()[1].querySelector('.ln-disc').value === '');
  fire(doc.getElementById('f_customerId'), String(custId), 'change');
  doc.getElementById('qForm').dispatchEvent(new win.Event('submit', { cancelable: true })); await wait(180);
  const q = (await win.DB.dbGetAll('quotations'))[0];
  let printed = '';
  win.open = () => ({ document: { write: (h) => { printed = h; }, close: () => {} } });
  await win.Print.printQuotation(q, { companyName: 'Shorr' });
  const prow = printed.split('<tr>').filter(r => /Priced item|In the lot item/.test(r));
  const cells = (r) => [...r.matchAll(/<td class="p-num">(.*?)<\/td>/g)].map(m => m[1]);
  console.log('5 print: priced line shows its discount; blank-price line prints blank price, Disc. and Amount:', cells(prow[0])[2] === '10%' && cells(prow[1])[1] === '' && cells(prow[1])[2] === '' && cells(prow[1])[3] === '', JSON.stringify(prow.map(cells)));
  await go('#/quotations/' + q.id, 120);
  const trs = [...doc.querySelectorAll('#content table tbody tr')].filter(t => /In the lot item|Priced item/.test(t.textContent));
  console.log('6 quotation detail page: blank-price line has no discount shown:', trs.length === 2 && !/5%/.test(trs[1].textContent) && /10%/.test(trs[0].textContent));
}
main().catch(e => { console.log('TEST FAILED', e); process.exit(1); });
